#!/bin/zsh
# Builds build/dotbar.app. Signs with $SIGN_IDENTITY when it exists in the login keychain (default: the local
# "dotbar local signing" certificate, which keeps the Accessibility grant across rebuilds); a Developer ID
# identity additionally gets the hardened runtime and a timestamp, which is what Apple notarization requires.
# Pass --install to also copy it to ~/Applications and launch it.
# SPARKLE=1 embeds Sparkle (updates): fetches the framework, links the updater and adds the SU* keys —
# the distribution DMG (make-dmg.sh) sets it.
set -euo pipefail
cd "${0:A:h:h}"
SPARKLE="${SPARKLE:-0}"
mkdir -p build
if [[ "$SPARKLE" == 1 ]]; then ./scripts/fetch-sparkle.sh; fi
swift scripts/make-icon.swift build/AppIcon.iconset >/dev/null
iconutil -c icns build/AppIcon.iconset -o build/AppIcon.icns
SPARKLE_FLAGS=()
if [[ "$SPARKLE" == 1 ]]; then SPARKLE_FLAGS=(-F .build/sparkle -framework Sparkle); fi
if [[ "$SPARKLE" == 1 ]]; then BIN="build/dotbar-dist"; else BIN="build/dotbar"; fi
swiftc -O -swift-version 5 -target "$(uname -m)-apple-macosx14.0" Sources/dotbar/*.swift -o "$BIN" "${SPARKLE_FLAGS[@]}"
APP="build/dotbar.app"
rm -rf "$APP"
if [[ "$SPARKLE" == 1 ]]; then
  mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$APP/Contents/Frameworks"
else
  mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
fi
cp "$BIN" "$APP/Contents/MacOS/dotbar"
cp build/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
# Donation QR for the About window: committed asset generated by
# scripts/make-qr.swift (self-verifying); regenerate only if the PayPal
# link ever changes.
cp assets/paypal-qr.png "$APP/Contents/Resources/paypal-qr.png"
SPARKLE_PLIST_KEYS=""
if [[ "$SPARKLE" == 1 ]]; then
  # Sparkle is a dynamic framework at @executable_path/../Frameworks; it carries its XPC
  # services and the Autoupdate helper, so the whole framework is copied. Same SU* keys
  # and shared EdDSA public key as usagebar/NeverSleep (updates from the repo appcast).
  cp -R .build/sparkle/Sparkle.framework "$APP/Contents/Frameworks/"
  install_name_tool -add_rpath "@executable_path/../Frameworks" "$APP/Contents/MacOS/dotbar" 2>/dev/null || true
  SPARKLE_PLIST_KEYS="
  <key>SUFeedURL</key><string>https://raw.githubusercontent.com/Marcus1571/dotbar/main/appcast.xml</string>
  <key>SUPublicEDKey</key><string>4X6j0DXdJCmcxqe3fkMKWxKuuHhhM+rYrK5LauHe9UA=</string>
  <key>SUEnableAutomaticChecks</key><true/>
  <key>SUScheduledCheckInterval</key><integer>604800</integer>
  <key>SUAutomaticallyUpdate</key><true/>"
fi
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleIdentifier</key><string>local.dotbar</string>
  <key>CFBundleName</key><string>dotbar</string>
  <key>CFBundleDisplayName</key><string>dotbar</string>
  <key>CFBundleExecutable</key><string>dotbar</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundleShortVersionString</key><string>0.7.0</string>
  <key>CFBundleVersion</key><string>0.7.0</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSHumanReadableCopyright</key><string>© 2026 Marcus1571</string>${SPARKLE_PLIST_KEYS}
</dict></plist>
PLIST
# Sign deepest-first: the Sparkle framework (XPC services, Updater.app, Autoupdate helper)
# needs a valid signature before the app can even attempt notarization.
if [[ "$SPARKLE" == 1 ]]; then
  if [[ "$SIGN_IDENTITY" == "-" ]]; then
    codesign --force --deep --sign - "$APP/Contents/Frameworks/Sparkle.framework"
    codesign --force --deep --sign - "$APP"
  else
    codesign --force --options runtime --timestamp --deep --sign "$SIGN_IDENTITY" "$APP/Contents/Frameworks/Sparkle.framework"
    codesign --force --options runtime --timestamp --sign "$SIGN_IDENTITY" "$APP"
  fi
else
  IDENTITY="${SIGN_IDENTITY:-dotbar local signing}"
  security find-identity -p codesigning | grep -q "\"$IDENTITY\"" || IDENTITY="-"
  if [[ "$IDENTITY" == "-" ]]; then
    codesign --force --sign - "$APP"
  elif [[ "$IDENTITY" == "Developer ID"* ]]; then
    codesign --force --options runtime --timestamp --sign "$IDENTITY" "$APP"
  else
    codesign --force --sign "$IDENTITY" "$APP"
  fi
fi
echo "Built $APP"
if [[ "${1:-}" == "--install" ]]; then
  pkill -x dotbar 2>/dev/null || true
  mkdir -p "$HOME/Applications"; rm -rf "$HOME/Applications/dotbar.app"
  cp -R "$APP" "$HOME/Applications/dotbar.app"
  open "$HOME/Applications/dotbar.app"
  echo "Installed and launched ~/Applications/dotbar.app"
fi
